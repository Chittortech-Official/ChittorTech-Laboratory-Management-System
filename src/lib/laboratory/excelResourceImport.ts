const MONTH_MAP: Record<string, number> = {
  jan: 1, january: 1,
  feb: 2, february: 2,
  mar: 3, march: 3,
  apr: 4, april: 4,
  may: 5,
  jun: 6, june: 6,
  jul: 7, july: 7,
  aug: 8, august: 8,
  sep: 9, sept: 9, september: 9,
  oct: 10, october: 10,
  nov: 11, november: 11,
  dec: 12, december: 12,
};

function pad2(n: number): string {
  return String(n).padStart(2, '0');
}

function validYmd(y: number, m: number, d: number): string | null {
  if (y < 1980 || y > 2100 || m < 1 || m > 12 || d < 1 || d > 31) return null;
  const dt = new Date(Date.UTC(y, m - 1, d));
  if (
    dt.getUTCFullYear() !== y ||
    dt.getUTCMonth() + 1 !== m ||
    dt.getUTCDate() !== d
  ) {
    return null;
  }
  return `${y}-${pad2(m)}-${pad2(d)}`;
}

/**
 * Normalizes messy Excel date formats (DD-MM-YYYY, DD/MM/YY, DD.MM.YYYY, DD-MMM-YYYY, YYYY-MM-DD, Excel serial) to YYYY-MM-DD.
 */
export function normalizeExcelDate(raw: unknown): string | null {
  if (raw === null || raw === undefined) return null;
  if (raw instanceof Date && !isNaN(raw.getTime())) {
    return validYmd(raw.getFullYear(), raw.getMonth() + 1, raw.getDate());
  }

  const str = String(raw).trim();
  if (!str || /^(-|na|n\/a|nil|none|pending|not applicable)$/i.test(str)) return null;

  // Excel numeric serial date (e.g. 45890)
  if (/^\d{5}(\.\d+)?$/.test(str)) {
    const serial = Math.floor(Number(str));
    if (serial > 25000 && serial < 75000) {
      const utcMs = Date.UTC(1899, 11, 30) + serial * 86_400_000;
      const dt = new Date(utcMs);
      return validYmd(dt.getUTCFullYear(), dt.getUTCMonth() + 1, dt.getUTCDate());
    }
  }

  // ISO YYYY-MM-DD or YYYY/MM/DD
  let m = str.match(/^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})(?:[T\s].*)?$/);
  if (m) {
    return validYmd(Number(m[1]), Number(m[2]), Number(m[3]));
  }

  // Indian DD-MM-YYYY, DD/MM/YYYY, DD.MM.YYYY, DD-MM-YY
  m = str.match(/^(\d{1,2})[-/.](\d{1,2})[-/.](\d{2,4})$/);
  if (m) {
    const first = Number(m[1]);
    const second = Number(m[2]);
    let year = Number(m[3]);
    if (year < 100) year += year >= 70 ? 1900 : 2000;
    // Prefer DD-MM-YYYY (Indian lab sheets) unless second > 12 (then MM-DD-YYYY)
    if (second <= 12) return validYmd(year, second, first);
    return validYmd(year, first, second);
  }

  // 15-Aug-2025 or 15 Aug 25
  m = str.match(/^(\d{1,2})[-/\s]([A-Za-z]{3,9})[-/\s,](\d{2,4})$/);
  if (m) {
    const month = MONTH_MAP[m[2].toLowerCase()];
    if (month) {
      let year = Number(m[3]);
      if (year < 100) year += year >= 70 ? 1900 : 2000;
      return validYmd(year, month, Number(m[1]));
    }
  }

  // Aug-2026 or Aug 26 -> default day 01
  m = str.match(/^([A-Za-z]{3,9})[-/\s](\d{2,4})$/);
  if (m) {
    const month = MONTH_MAP[m[1].toLowerCase()];
    if (month) {
      let year = Number(m[2]);
      if (year < 100) year += year >= 70 ? 1900 : 2000;
      return validYmd(year, month, 1);
    }
  }

  return null;
}

function normHeader(h: string): string {
  return h
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function pickBestHeader(headers: string[], patterns: RegExp[], exclude: RegExp[] = []): string | null {
  for (const pat of patterns) {
    const found = headers.find((h) => {
      const nh = normHeader(h);
      if (exclude.some((ex) => ex.test(nh))) return false;
      return pat.test(nh);
    });
    if (found) return found;
  }
  return null;
}

function detectSheetModule(headers: string[]): ResourceSubModule {
  const joined = headers.map(normHeader).join(' | ');
  if (/\b(doc code|document code|sop|revision|effective date|review due|prepared by|approved by)\b/.test(joined)) {
    return 'documents';
  }
  if (/\b(staff|employee|designation|trainer|training|competency|qualified test|assessment)\b/.test(joined)) {
    return 'staff';
  }
  return 'equipment';
}

/**
 * Fast, reliable deterministic fallback mapper when AI is unavailable or offline.
 */
export function buildHeuristicMapping(
  headers: string[],
  targetModule: ResourceSubModule
): ExcelColumnMapping {
  const detectedModule = detectSheetModule(headers);
  const usedHeaders = new Set<string>();
  const claim = (h: string | null): string | null => {
    if (h) usedHeaders.add(h);
    return h;
  };

  if (targetModule === 'equipment') {
    const rowSrPattern = /^(s no|sr no|sl no|serial|s\.?\s*no\.?)$/;
    const eqCode = claim(
      pickBestHeader(
        headers,
        [
          /\b(equipment code|equip code|eq code|instrument code|inst code|asset code|asset id|equipment id|lab id|id no|tag no)\b/,
          /\b(code)\b/,
        ],
        [rowSrPattern]
      )
    );
    const name = claim(
      pickBestHeader(headers, [
        /\b(equipment name|name of equipment|instrument name|name of instrument|apparatus|description|particulars|item name)\b/,
        /\b(equipment|instrument|name)\b/,
      ])
    );

    const makeModelHeader = pickBestHeader(headers, [/\b(make model|make and model|manufacturer model)\b/]);
    let manufacturer: string | null = null;
    let model: string | null = null;
    let splitMakeModelColumn: string | null = null;

    if (makeModelHeader) {
      usedHeaders.add(makeModelHeader);
      splitMakeModelColumn = makeModelHeader;
    } else {
      manufacturer = claim(
        pickBestHeader(headers, [/\b(manufacturer|make|brand|oem|supplier|company)\b/])
      );
      model = claim(
        pickBestHeader(headers, [/\b(model no|model number|model|type)\b/])
      );
    }

    const serialNumber = claim(
      pickBestHeader(
        headers,
        [/\b(serial no|serial number|sr number|machine serial|mfg sr)\b/],
        [/^(s no|sr no|sl no)$/]
      )
    );
    const location = claim(
      pickBestHeader(headers, [/\b(location|department|section|lab area|room|placed at)\b/])
    );
    const lastCal = claim(
      pickBestHeader(headers, [
        /\b(last cal|last calibration|calibration date|cal date|date of calibration|done on)\b/,
      ])
    );
    const nextCal = claim(
      pickBestHeader(headers, [
        /\b(next cal|calibration due|due date|next due|valid upto|valid up to|validity|expiry)\b/,
      ])
    );
    const agency = claim(
      pickBestHeader(headers, [/\b(calibration agency|cal agency|calibrated by|agency|external lab)\b/])
    );
    const cert = claim(
      pickBestHeader(headers, [/\b(certificate no|cert no|certificate number|cal cert|report no)\b/])
    );
    const notes = claim(
      pickBestHeader(headers, [/\b(remarks|remark|notes|maintenance|comment|observation)\b/])
    );
    const status = claim(pickBestHeader(headers, [/\b(status|condition|state|working status)\b/]));

    const extraNoteColumns = headers.filter((h) => {
      if (usedHeaders.has(h)) return false;
      const nh = normHeader(h);
      // Skip pure row serial counter column
      if (/^(s|sr|sl)\s*(no|num|#)?$/.test(nh)) return false;
      return true;
    });

    return {
      fieldMap: {
        equipment_code: eqCode,
        name,
        manufacturer,
        model,
        serial_number: serialNumber,
        location,
        last_calibration_date: lastCal,
        next_calibration_date: nextCal,
        calibration_agency: agency,
        certificate_no: cert,
        maintenance_notes: notes,
        status,
      },
      extraNoteColumns,
      splitMakeModelColumn,
      detectedModule,
      analysisSummary:
        'Mapped Excel headers automatically using ChittorTech Laboratory Resource field rules.',
    };
  }

  if (targetModule === 'documents') {
    const docCode = claim(pickBestHeader(headers, [/\b(doc code|document code|doc no|document no|code|sop no)\b/]));
    const title = claim(pickBestHeader(headers, [/\b(title|document name|sop name|name|subject)\b/]));
    const category = claim(pickBestHeader(headers, [/\b(category|doc type|type)\b/]));
    const version = claim(pickBestHeader(headers, [/\b(version|issue no|ver)\b/]));
    const rev = claim(pickBestHeader(headers, [/\b(revision|rev no|rev)\b/]));
    const eff = claim(pickBestHeader(headers, [/\b(effective date|issue date|date of issue)\b/]));
    const due = claim(pickBestHeader(headers, [/\b(review due|next review|valid upto|due date)\b/]));
    const prep = claim(pickBestHeader(headers, [/\b(prepared by|author)\b/]));
    const revBy = claim(pickBestHeader(headers, [/\b(reviewed by|checked by)\b/]));
    const appBy = claim(pickBestHeader(headers, [/\b(approved by|authorized by)\b/]));
    const std = claim(pickBestHeader(headers, [/\b(standard|bis|iso|reference|clause)\b/]));
    const summary = claim(pickBestHeader(headers, [/\b(summary|scope|description)\b/]));
    const remarks = claim(pickBestHeader(headers, [/\b(remarks|notes|comment)\b/]));
    const status = claim(pickBestHeader(headers, [/\b(status|state)\b/]));

    const extraNoteColumns = headers.filter(
      (h) => !usedHeaders.has(h) && !/^(s|sr|sl)\s*(no|num|#)?$/.test(normHeader(h))
    );

    return {
      fieldMap: {
        doc_code: docCode,
        title,
        category,
        version,
        revision_number: rev,
        effective_date: eff,
        review_due_date: due,
        prepared_by: prep,
        reviewed_by: revBy,
        approved_by: appBy,
        standard_ref: std,
        summary,
        remarks,
        status,
      },
      extraNoteColumns,
      detectedModule,
      analysisSummary: 'Mapped Document & SOP columns automatically.',
    };
  }

  // Staff Training & Competency
  const staffName = claim(pickBestHeader(headers, [/\b(staff name|employee name|name|chemist|technician|personnel)\b/]));
  const empId = claim(pickBestHeader(headers, [/\b(employee id|emp id|emp code|staff id)\b/]));
  const designation = claim(pickBestHeader(headers, [/\b(designation|role|title|position)\b/]));
  const tests = claim(pickBestHeader(headers, [/\b(qualified test|authorized test|test method|parameters|scope)\b/]));
  const topic = claim(pickBestHeader(headers, [/\b(training topic|topic|program|course|module)\b/]));
  const trDate = claim(pickBestHeader(headers, [/\b(training date|date of training|completed on)\b/]));
  const score = claim(pickBestHeader(headers, [/\b(assessment|score|result|marks|grade)\b/]));
  const compStatus = claim(pickBestHeader(headers, [/\b(competency|status|state)\b/]));
  const validUntil = claim(pickBestHeader(headers, [/\b(valid until|valid upto|re evaluation|due date|expiry)\b/]));
  const trainer = claim(pickBestHeader(headers, [/\b(trainer|faculty|instructor)\b/]));
  const certRef = claim(pickBestHeader(headers, [/\b(certificate|cert ref|cert no)\b/]));
  const appBy = claim(pickBestHeader(headers, [/\b(approved by|authorized by)\b/]));
  const notes = claim(pickBestHeader(headers, [/\b(notes|remarks|comment)\b/]));

  const extraNoteColumns = headers.filter(
    (h) => !usedHeaders.has(h) && !/^(s|sr|sl)\s*(no|num|#)?$/.test(normHeader(h))
  );

  return {
    fieldMap: {
      staff_name: staffName,
      employee_id: empId,
      designation,
      qualified_tests: tests,
      training_topic: topic,
      training_date: trDate,
      assessment_score: score,
      competency_status: compStatus,
      valid_until: validUntil,
      trainer_name: trainer,
      certificate_ref: certRef,
      approved_by: appBy,
      notes,
    },
    extraNoteColumns,
    detectedModule,
    analysisSummary: 'Mapped Staff Training & Competency columns automatically.',
  };
}

function splitMakeAndModel(raw: string): { manufacturer: string | null; model: string | null } {
  const clean = raw.trim();
  if (!clean || /^(-|na|n\/a|nil)$/i.test(clean)) return { manufacturer: null, model: null };
  const sepMatch = clean.match(/^(.+?)\s*(?:\/|\||–|-|,)\s*(.+)$/);
  if (sepMatch) {
    return {
      manufacturer: sepMatch[1].trim() || null,
      model: sepMatch[2].trim() || null,
    };
  }
  return { manufacturer: clean, model: null };
}

function normalizeEquipmentStatus(
  rawStatus: string,
  nextCalDate: string | null
): 'Active' | 'Calibration Due' | 'Under Maintenance' | 'Out of Service' {
  const s = rawStatus.toLowerCase().trim();
  if (/(out of service|condemned|scrap|retired|decommission|not working|inactive)/.test(s)) {
    return 'Out of Service';
  }
  if (/(maintenance|repair|servicing|breakdown)/.test(s)) {
    return 'Under Maintenance';
  }
  if (/(due|overdue|expired|pending cal)/.test(s)) {
    return 'Calibration Due';
  }
  if (nextCalDate) {
    const dueMs = new Date(`${nextCalDate}T00:00:00Z`).getTime();
    const todayMs = new Date().setHours(0, 0, 0, 0);
    if (!isNaN(dueMs) && dueMs < todayMs) {
      return 'Calibration Due';
    }
  }
  return 'Active';
}

function normalizeDocCategory(raw: string): 'SOP' | 'Quality Manual' | 'Test Method' | 'Work Instruction' | 'Form / Record' {
  const s = raw.toLowerCase();
  if (s.includes('manual')) return 'Quality Manual';
  if (s.includes('method') || s.includes('test')) return 'Test Method';
  if (s.includes('work') || s.includes('instruction')) return 'Work Instruction';
  if (s.includes('form') || s.includes('record') || s.includes('format')) return 'Form / Record';
  return 'SOP';
}

function normalizeDocStatus(raw: string): 'Draft' | 'Under Review' | 'Approved' | 'Obsolete' {
  const s = raw.toLowerCase();
  if (s.includes('obsolete') || s.includes('superseded') || s.includes('archived')) return 'Obsolete';
  if (s.includes('review')) return 'Under Review';
  if (s.includes('draft')) return 'Draft';
  return 'Approved';
}

function normalizeStaffStatus(raw: string, validUntil: string | null): 'In Training' | 'Competent' | 'Re-evaluation Due' {
  const s = raw.toLowerCase();
  if (s.includes('training') || s.includes('probation') || s.includes('trainee')) return 'In Training';
  if (s.includes('due') || s.includes('re-eval') || s.includes('expired')) return 'Re-evaluation Due';
  if (validUntil) {
    const dueMs = new Date(`${validUntil}T00:00:00Z`).getTime();
    if (!isNaN(dueMs) && dueMs < Date.now()) return 'Re-evaluation Due';
  }
  return 'Competent';
}

function sanitizeCodeToken(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[^A-Z0-9-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 28);
}

/**
 * Applies the verified column mapping across all Excel rows cleanly and validates each row for Supabase insertion.
 */
export function applyColumnMappingToRows(params: {
  targetModule: ResourceSubModule;
  rows: Record<string, string>[];
  mapping: ExcelColumnMapping;
  existingKeys: Set<string>;
}): NormalizedImportRow[] {
  const { targetModule, rows, mapping, existingKeys } = params;
  const fm = mapping.fieldMap || {};
  const getVal = (row: Record<string, string>, field: string): string => {
    const col = fm[field];
    if (!col) return '';
    return String(row[col] ?? '').trim();
  };

  const buildExtras = (row: Record<string, string>, existingNotes: string): string | null => {
    const parts: string[] = [];
    if (existingNotes) parts.push(existingNotes);
    for (const col of mapping.extraNoteColumns || []) {
      const val = String(row[col] ?? '').trim();
      if (val && !/^(-|na|n\/a|nil)$/i.test(val)) {
        parts.push(`${col}: ${val}`);
      }
    }
    return parts.length > 0 ? parts.join(' | ') : null;
  };

  const seenCodes = new Set<string>();
  const out: NormalizedImportRow[] = [];

  rows.forEach((row, idx) => {
    const warnings: string[] = [];

    if (targetModule === 'equipment') {
      const name = getVal(row, 'name');
      if (!name) return; // skip blank/header echo lines

      let code = getVal(row, 'equipment_code');
      let autoGeneratedCode = false;
      if (!code || /^(-|na|n\/a|nil)$/i.test(code)) {
        const prefix = sanitizeCodeToken(name.split(/\s+/).slice(0, 2).join('-')) || 'EQ';
        code = `EQ-${prefix.slice(0, 8)}-${String(idx + 1).padStart(3, '0')}`;
        autoGeneratedCode = true;
        warnings.push('Auto-generated Equipment Code');
      }

      let manufacturer = getVal(row, 'manufacturer') || null;
      let model = getVal(row, 'model') || null;
      if (mapping.splitMakeModelColumn) {
        const split = splitMakeAndModel(String(row[mapping.splitMakeModelColumn] ?? ''));
        manufacturer = manufacturer || split.manufacturer;
        model = model || split.model;
      }

      const rawLast = getVal(row, 'last_calibration_date');
      const rawNext = getVal(row, 'next_calibration_date');
      const lastCal = normalizeExcelDate(rawLast);
      const nextCal = normalizeExcelDate(rawNext);
      if (rawLast && !lastCal) warnings.push(`Unparsed Last Cal date: "${rawLast}"`);
      if (rawNext && !nextCal) warnings.push(`Unparsed Due Date: "${rawNext}"`);

      const status = normalizeEquipmentStatus(getVal(row, 'status'), nextCal);
      if (status === 'Calibration Due') warnings.push('Marked Calibration Due');

      const normKey = `${code.toLowerCase()}|${name.toLowerCase()}`;
      const isDuplicate =
        existingKeys.has(code.toLowerCase()) || seenCodes.has(normKey);
      seenCodes.add(normKey);
      if (isDuplicate) warnings.push('Already exists in register');

      out.push({
        rowIndex: idx + 1,
        record: {
          equipment_code: code,
          name,
          manufacturer,
          model,
          serial_number: getVal(row, 'serial_number') || null,
          location: getVal(row, 'location') || null,
          last_calibration_date: lastCal,
          next_calibration_date: nextCal,
          calibration_agency: getVal(row, 'calibration_agency') || null,
          certificate_no: getVal(row, 'certificate_no') || null,
          maintenance_notes: buildExtras(row, getVal(row, 'maintenance_notes')),
          status,
        },
        warnings,
        isDuplicate,
        autoGeneratedCode,
        selected: !isDuplicate,
      });
      return;
    }

    if (targetModule === 'documents') {
      const title = getVal(row, 'title');
      if (!title) return;

      let code = getVal(row, 'doc_code');
      let autoGeneratedCode = false;
      if (!code) {
        code = `CT-DOC-${String(idx + 1).padStart(3, '0')}`;
        autoGeneratedCode = true;
        warnings.push('Auto-generated Document Code');
      }

      const eff = normalizeExcelDate(getVal(row, 'effective_date'));
      const due = normalizeExcelDate(getVal(row, 'review_due_date'));
      const isDuplicate = existingKeys.has(code.toLowerCase()) || seenCodes.has(code.toLowerCase());
      seenCodes.add(code.toLowerCase());
      if (isDuplicate) warnings.push('Duplicate Doc Code');

      out.push({
        rowIndex: idx + 1,
        record: {
          doc_code: code,
          title,
          category: normalizeDocCategory(getVal(row, 'category') || 'SOP'),
          version: getVal(row, 'version') || '1.0',
          revision_number: getVal(row, 'revision_number') || 'Rev 00',
          effective_date: eff,
          review_due_date: due,
          prepared_by: getVal(row, 'prepared_by') || null,
          reviewed_by: getVal(row, 'reviewed_by') || null,
          approved_by: getVal(row, 'approved_by') || null,
          standard_ref: getVal(row, 'standard_ref') || null,
          summary: getVal(row, 'summary') || null,
          remarks: buildExtras(row, getVal(row, 'remarks')),
          status: normalizeDocStatus(getVal(row, 'status') || 'Approved'),
        },
        warnings,
        isDuplicate,
        autoGeneratedCode,
        selected: !isDuplicate,
      });
      return;
    }

    // Staff Training & Competency
    const staffName = getVal(row, 'staff_name');
    if (!staffName) return;

    const trDate = normalizeExcelDate(getVal(row, 'training_date'));
    const validUntil = normalizeExcelDate(getVal(row, 'valid_until'));
    const empId = getVal(row, 'employee_id') || null;
    const dupKey = `${staffName.toLowerCase()}|${(empId || '').toLowerCase()}`;
    const isDuplicate = existingKeys.has(staffName.toLowerCase()) || seenCodes.has(dupKey);
    seenCodes.add(dupKey);
    if (isDuplicate) warnings.push('Staff record already exists');

    out.push({
      rowIndex: idx + 1,
      record: {
        staff_name: staffName,
        employee_id: empId,
        designation: getVal(row, 'designation') || 'QA Lab Chemist',
        qualified_tests: getVal(row, 'qualified_tests') || 'Cement & Materials QA Testing',
        training_topic: getVal(row, 'training_topic') || 'ISO/IEC 17025 Laboratory Competency',
        training_date: trDate,
        assessment_score: getVal(row, 'assessment_score') || null,
        competency_status: normalizeStaffStatus(getVal(row, 'competency_status'), validUntil),
        valid_until: validUntil,
        trainer_name: getVal(row, 'trainer_name') || null,
        certificate_ref: getVal(row, 'certificate_ref') || null,
        approved_by: getVal(row, 'approved_by') || null,
        notes: buildExtras(row, getVal(row, 'notes')),
      },
      warnings,
      isDuplicate,
      autoGeneratedCode: false,
      selected: !isDuplicate,
    });
  });

  return out;
}

